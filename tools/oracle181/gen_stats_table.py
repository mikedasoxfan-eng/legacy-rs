"""Turn tools/oracle181/statlist.txt (from `oracle.sh statlist`) into crates/worldgen181/src/stats_table.rs."""
import json
import os

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
rows = [l.rstrip('\n').split('\t') for l in open(os.path.join(root, 'tools/oracle181/statlist.txt'), encoding='utf-8')]


def rs(s):
    return json.dumps(s, ensure_ascii=False)


out = ['//! `StatList` as the original registers it (generated by tools/oracle181/gen_stats_table.py', '//! from `oracle.sh statlist`).', '']
out.append('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
out.append('pub enum StatType {')
out.append('    Simple,')
out.append('    Time,')
out.append('    Distance,')
out.append('}')
out.append('')
gen = [r for r in rows if r[0] == 'general']
out.append('/// `field_25187_b`: (stat id, type, translated name).')
out.append('pub const GENERAL: [(i32, StatType, &str); %d] = [' % len(gen))
for r in gen:
    out.append('    (%s, StatType::%s, %s),' % (r[1], r[2].capitalize(), rs(r[3])))
out.append('];')
out.append('')
for kind, doc in [('block', '`field_25185_d`: blocks with mining stats (stat id, block id).'),
                  ('item', '`field_25186_c`: items (id >= 256) with use stats (stat id, item id).')]:
    sel = [r for r in rows if r[0] == kind]
    out.append('/// ' + doc)
    out.append('pub const %sS: [(i32, i32); %d] = [' % (kind.upper(), len(sel)))
    for r in sel:
        out.append('    (%s, %s),' % (r[1], r[2]))
    out.append('];')
    out.append('')
for name, doc in [('mine', 'mineBlockStatArray'), ('craft', 'field_25158_z (crafted)'),
                  ('use', 'field_25172_A (used)'), ('break', 'field_25170_B (broken)')]:
    m = [(int(r[1]), int(r[2])) for r in rows if r[0] == name]
    out.append('/// `%s`: index -> stat id, after `replaceAllSimilarBlocks`.' % doc)
    out.append('pub const %s: [(i32, i32); %d] = [' % (name.upper(), len(m)))
    for a, b in m:
        out.append('    (%d, %d),' % (a, b))
    out.append('];')
    out.append('')
out.append('/// The stat a table maps `index` to, if the original registered one.')
out.append('pub fn lookup(table: &[(i32, i32)], index: i32) -> Option<i32> {')
out.append('    table.iter().find(|(i, _)| *i == index).map(|(_, s)| *s)')
out.append('}')
open(os.path.join(root, 'crates/worldgen181/src/stats_table.rs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', len(out), 'lines')
